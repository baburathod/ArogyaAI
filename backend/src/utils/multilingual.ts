/**
 * Get localized healthcare message
 */
export function getLocalizedMessage(
  key: string,
  language: 'en' | 'hi' | 'te' = 'en'
): string {
  const keys = key.split('.');
  let value: any = HealthcareTerms;

  for (const k of keys) {
    value = value?.[k];
  }

  if (value && typeof value === 'object') {
    return value[language] || value['en'] || 'Message not found';
  }

  return value || 'Message not found';
}

/**
 * Format severity level with emoji
 */
export function formatSeverity(level: 'low' | 'medium' | 'high' | 'critical'): string {
  const emojis = {
    low: '✅',
    medium: '⚠️',
    high: '🔴',
    critical: '🚨',
  };
  return `${emojis[level]} ${level.toUpperCase()}`;
}

/**
 * Get severity color for UI
 */
export function getSeverityColor(level: 'low' | 'medium' | 'high' | 'critical'): string {
  const colors = {
    low: '#10b981',    // green
    medium: '#f59e0b', // amber
    high: '#ef4444',   // red
    critical: '#7c2d12', // dark red
  };
  return colors[level];
}

/**
 * Translate emergency symptoms
 */
export function translateEmergencySymptoms(symptoms: string[], language: 'en' | 'hi' | 'te'): string[] {
  return symptoms.map((symptom) => {
    const key = symptom
      .toLowerCase()
      .replace(/\s+/g, '')
      .replace(/[^a-z0-9]/g, '');
    return getLocalizedMessage(`emergencyWarnings.${key}`, language) || symptom;
  });
}

